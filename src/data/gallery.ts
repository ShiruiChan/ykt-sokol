import { GALLERY, IMAGE_VARIANTS } from './image-variants';

export interface GalleryPhoto {
	src: string;
	width: number;
	height: number;
	alt: string;
}

/**
 * Подписи по сериям съёмки: [первый, последний кадр, описание].
 * Сюжет кадров один на серию, поэтому подпись общая, а номер уточняет кадр.
 */
const SERIES: [number, number, string][] = [
	[1, 2, 'Снегоболотоход ЯКТСокол с грузовой платформой в поле'],
	[3, 8, 'Снегоболотоход ЯКТСокол, вид сзади: грузовой отсек и задний борт'],
	[9, 9, 'Снегоболотоход ЯКТСокол, вид спереди: шины низкого давления'],
	[10, 11, 'Снегоболотоход ЯКТСокол сбоку на площадке у цеха'],
	[12, 13, 'Снегоболотоход ЯКТСокол в поле, вид в три четверти'],
	[14, 14, 'Подвеска и мосты снегоболотохода ЯКТСокол снизу'],
	[15, 26, 'Снегоболотоход ЯКТСокол в осенних камышах'],
	[27, 27, 'Кузов и канистры снегоболотохода ЯКТСокол крупным планом'],
	[28, 29, 'Снегоболотоход ЯКТСокол в осенних камышах'],
	[30, 53, 'Снегоболотоход ЯКТСокол рядом с бронетехникой на выставочной площадке'],
	[54, 54, 'Готовые снегоболотоходы ЯКТСокол с прицепами во дворе производства'],
	[55, 64, 'Снегоболотоход ЯКТСокол с прицепом в осеннем поле'],
	[65, 65, 'Снегоболотоход ЯКТСокол с грузовой платформой в поле, вид сбоку'],
];

function caption(n: number): string {
	const s = SERIES.find(([from, to]) => n >= from && n <= to);
	return `${s ? s[2] : 'Снегоболотоход ЯКТСокол'} — кадр ${n}`;
}

// Номер кадра берём из имени файла («/gallery/27.webp» → 27): после удаления
// повторов в нумерации есть пропуски, и порядковый индекс дал бы чужую подпись
export const GALLERY_PHOTOS: GalleryPhoto[] = GALLERY.map((src, i) => {
	const v = IMAGE_VARIANTS[src];
	const n = Number(src.match(/(\d+)\.webp$/)?.[1] ?? i + 1);
	return { src, width: v.w, height: v.h, alt: caption(n) };
});

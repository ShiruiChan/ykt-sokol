import { GALLERY, IMAGE_VARIANTS } from './image-variants';

export interface GalleryPhoto {
	src: string;
	width: number;
	height: number;
	alt: string;
}

/**
 * Подписи по сериям съёмки: [первый, последний кадр, описание].
 * Сюжет кадров один на серию, поэтому подпись общая, а номер уточняет кадр.
 */
const SERIES: [number, number, string][] = [
	[1, 2, 'Снегоболотоход СОКОЛ с грузовой платформой в поле'],
	[3, 8, 'Снегоболотоход СОКОЛ, вид сзади: грузовой отсек и задний борт'],
	[9, 9, 'Снегоболотоход СОКОЛ, вид спереди: шины низкого давления'],
	[10, 11, 'Снегоболотоход СОКОЛ сбоку на площадке у цеха'],
	[12, 13, 'Снегоболотоход СОКОЛ в поле, вид в три четверти'],
	[14, 14, 'Подвеска и мосты снегоболотохода СОКОЛ снизу'],
	[15, 26, 'Снегоболотоход СОКОЛ в осенних камышах'],
	[27, 27, 'Кузов и канистры снегоболотохода СОКОЛ крупным планом'],
	[28, 29, 'Снегоболотоход СОКОЛ в осенних камышах'],
	[30, 53, 'Снегоболотоход СОКОЛ рядом с бронетехникой на выставочной площадке'],
	[54, 54, 'Готовые снегоболотоходы СОКОЛ с прицепами во дворе производства'],
	[55, 64, 'Снегоболотоход СОКОЛ с прицепом в осеннем поле'],
	[65, 65, 'Снегоболотоход СОКОЛ с грузовой платформой в поле, вид сбоку'],
];

function caption(n: number): string {
	const s = SERIES.find(([from, to]) => n >= from && n <= to);
	return `${s ? s[2] : 'Снегоболотоход СОКОЛ'} — кадр ${n}`;
}

export const GALLERY_PHOTOS: GalleryPhoto[] = GALLERY.map((src, i) => {
	const v = IMAGE_VARIANTS[src];
	return { src, width: v.w, height: v.h, alt: caption(i + 1) };
});
